// Package bundle turns a tree of Lua modules into one self-contained
// script, because DCS missions can only embed and run single files.
package bundle

import (
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/behringer24/DCS-Tarmac/internal/luasrc"
	"github.com/behringer24/DCS-Tarmac/internal/project"
	"github.com/yuin/gopher-lua/parse"
)

// Module is one Lua source file. Its name follows the require convention:
// src/tarmac/log.lua becomes "tarmac.log", src/tarmac/init.lua "tarmac".
type Module struct {
	Name     string
	Path     string
	Display  string
	Source   string
	Requires []string
}

// Discover finds all modules below the given source roots.
func Discover(roots []string) (map[string]*Module, error) {
	modules := map[string]*Module{}
	for _, root := range roots {
		err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() || !strings.HasSuffix(path, ".lua") {
				return nil
			}
			rel, err := filepath.Rel(root, path)
			if err != nil {
				return err
			}
			rel = filepath.ToSlash(rel)
			name := strings.TrimSuffix(rel, ".lua")
			if name == "init" {
				return fmt.Errorf("%s: init.lua must live in a module directory", path)
			}
			name = strings.TrimSuffix(name, "/init")
			name = strings.ReplaceAll(name, "/", ".")

			raw, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			src := strings.TrimPrefix(string(raw), "\uFEFF")
			src = strings.ReplaceAll(src, "\r\n", "\n")

			if other, ok := modules[name]; ok {
				return fmt.Errorf("module %q defined twice: %s and %s", name, other.Path, path)
			}
			modules[name] = &Module{Name: name, Path: path, Display: rel, Source: src}
			return nil
		})
		if err != nil {
			return nil, err
		}
	}
	return modules, nil
}

// Check validates a module: it must parse, must not use syntax newer than
// Lua 5.1 and its literal require calls are recorded.
func Check(m *Module) error {
	tokens, err := luasrc.Tokenize(m.Source)
	if err != nil {
		return fmt.Errorf("%s: %w", m.Path, err)
	}
	m.Requires = luasrc.Requires(tokens)
	if _, err := parse.Parse(strings.NewReader(m.Source), m.Path); err != nil {
		return fmt.Errorf("%s: %w", m.Path, err)
	}
	if problems := luasrc.Lua51Problems(tokens); len(problems) > 0 {
		return fmt.Errorf("%s:\n  %s", m.Path, strings.Join(problems, "\n  "))
	}
	return nil
}

// CheckAll validates every module and returns all errors found.
func CheckAll(modules map[string]*Module) []error {
	var errs []error
	for _, name := range sortedNames(modules) {
		if err := Check(modules[name]); err != nil {
			errs = append(errs, err)
		}
	}
	return errs
}

// Resolve returns the modules reachable from entry, dependencies first.
// Missing modules and require cycles are reported as errors.
func Resolve(modules map[string]*Module, entry string) ([]*Module, error) {
	var ordered []*Module
	state := map[string]int{} // 1 = visiting, 2 = done
	var visit func(name string, stack []string) error
	visit = func(name string, stack []string) error {
		switch state[name] {
		case 2:
			return nil
		case 1:
			return fmt.Errorf("require cycle: %s -> %s", strings.Join(stack, " -> "), name)
		}
		m, ok := modules[name]
		if !ok {
			if len(stack) == 0 {
				return fmt.Errorf("entry module %q not found", name)
			}
			return fmt.Errorf("module %q required by %q not found", name, stack[len(stack)-1])
		}
		state[name] = 1
		for _, dep := range m.Requires {
			if err := visit(dep, append(stack, name)); err != nil {
				return err
			}
		}
		state[name] = 2
		ordered = append(ordered, m)
		return nil
	}
	if err := visit(entry, nil); err != nil {
		return nil, err
	}
	return ordered, nil
}

const prelude = `do
local __modules, __loaded = {}, {}

local function require(name)
    local value = __loaded[name]
    if value ~= nil then
        return value
    end
    local loader = __modules[name]
    if loader == nil then
        error("module '" .. tostring(name) .. "' is not part of this bundle", 2)
    end
    value = loader(name)
    if value == nil then
        value = true
    end
    __loaded[name] = value
    return value
end
`

// Render produces the bundled script.
func Render(p *project.Project, ordered []*Module) string {
	var b strings.Builder
	for _, line := range p.Banner {
		b.WriteString("-- " + line + "\n")
	}
	fmt.Fprintf(&b, "-- Generated by tarmac from %d modules (entry %q).\n", len(ordered), p.Entry)
	b.WriteString("-- Do not edit this file, change the module sources and rebuild.\n\n")
	b.WriteString(prelude)
	for _, m := range ordered {
		fmt.Fprintf(&b, "\n-- module %s (%s)\n", m.Name, m.Display)
		fmt.Fprintf(&b, "__modules[%q] = function(...)\n", m.Name)
		b.WriteString(strings.TrimRight(m.Source, "\n"))
		b.WriteString("\nend\n")
	}
	fmt.Fprintf(&b, "\nrequire(%q)\nend\n", p.Entry)
	return b.String()
}

// Result describes a finished build.
type Result struct {
	Output  string
	Modules []*Module
}

// Build checks, resolves and renders the project and writes the output.
func Build(p *project.Project) (*Result, error) {
	modules, err := Discover(p.Sources)
	if err != nil {
		return nil, err
	}
	for _, m := range modules {
		if err := Check(m); err != nil {
			return nil, err
		}
	}
	ordered, err := Resolve(modules, p.Entry)
	if err != nil {
		return nil, err
	}
	out := Render(p, ordered)
	if _, err := parse.Parse(strings.NewReader(out), p.Output); err != nil {
		return nil, fmt.Errorf("bundle does not parse: %w", err)
	}
	if err := os.MkdirAll(filepath.Dir(p.Output), 0o755); err != nil {
		return nil, err
	}
	if err := os.WriteFile(p.Output, []byte(out), 0o644); err != nil {
		return nil, err
	}
	return &Result{Output: p.Output, Modules: ordered}, nil
}

func sortedNames(modules map[string]*Module) []string {
	names := make([]string, 0, len(modules))
	for name := range modules {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}
